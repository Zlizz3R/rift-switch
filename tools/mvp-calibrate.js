// node tools/mvp-calibrate.js [data folder] – the figures behind MVP and ACE (ui/mvp.js) from the
// stored Summoner's Rift games: for every role and result (won / lost) the usual value and spread of
// each part, then the quantiles of the weighted sum, then a small offset per role so that every role
// is MVP and ACE equally often. Only the OTHER players set the figures – the own accounts are left
// out (a smurf would move them), and MVP / ACE are counted in games without an own account. Writes
// ui/mvp-rules.js and prints how often each role is MVP / ACE. Reads the data folder only.
const fs = require('fs'), path = require('path');
const UI = path.join(__dirname, '..', 'ui') + path.sep;
const St = require(UI + 'stats.js');
const Mvp = require(UI + 'mvp.js');
const DATA = process.argv[2] || path.join(process.env.APPDATA || '', 'rift-switch');
const own = new Set(Object.keys(JSON.parse(fs.readFileSync(path.join(DATA, 'matches', 'by.json'), 'utf8'))));
const NQ = 40;

// every full Summoner's Rift game once: ten players with their details, 15 minutes or more
const games = new Map();
for (const f of [path.join(DATA, 'matches', 'games.jsonl'), path.join(DATA, 'matches-others', 'games.jsonl')]) {
  if (!fs.existsSync(f)) continue;
  for (const l of fs.readFileSync(f, 'utf8').split('\n')) {
    if (!l.trim()) continue;
    let g; try { g = JSON.parse(l); } catch { continue; }
    if (!g || g.lite || g.mode !== 'CLASSIC' || St.isRemake(g) || (g.dur || 0) < 900) continue;
    if (!g.players || g.players.length !== 10 || !g.players.every(p => p.x && Number.isFinite(p.k))) continue;
    if (!games.has(String(g.id))) games.set(String(g.id), g);
  }
}
const sets = [];
for (const g of games.values()) {
  const rows = Mvp.features(g);
  if (rows) sets.push({ g, rows: rows.map((x, i) => ({ ...x, own: own.has(g.players[i].puuid) })) });
}
const others = sets.flatMap(s => s.rows).filter(x => !x.own);
const groups = [...new Set(others.map(Mvp.groupOf))].sort();
const sig = v => +v.toPrecision(4);

// 1. the usual value and spread of every part, per role and result
const norm = {};
for (const k of groups) {
  norm[k] = {};
  const rows = others.filter(x => Mvp.groupOf(x) === k);
  for (const f of Mvp.FEAT) {
    const v = rows.map(x => x[f]).filter(x => x != null);
    const m = v.reduce((s, a) => s + a, 0) / v.length;
    norm[k][f] = [sig(m), sig(Math.sqrt(v.reduce((s, a) => s + (a - m) ** 2, 0) / v.length) || 1)];
  }
}
// 2. the quantiles of the weighted sum
const quant = {};
for (const k of groups) {
  const v = others.filter(x => Mvp.groupOf(x) === k).map(x => Mvp.raw(x, norm)).sort((a, b) => a - b);
  quant[k] = Array.from({ length: NQ + 1 }, (_, i) => +v[Math.round((i / NQ) * (v.length - 1))].toFixed(4));
}
// 3. the offset per role: MVP and ACE equally often (in the games without an own account)
const roles = St.POSITIONS;
const plain = sets.filter(s => !s.rows.some(x => x.own));
function shares(R) {
  const mvp = Object.fromEntries(roles.map(r => [r, 0])), ace = { ...mvp };
  for (const { rows } of plain) {
    const s = Mvp.scoreRows(rows, R);
    const best = win => rows.map((x, i) => i).filter(i => rows[i].win === win).sort((a, b) => s[b] - s[a])[0];
    const m = best(true), a = best(false);
    if (m != null) mvp[rows[m].role]++;
    if (a != null) ace[rows[a].role]++;
  }
  return { mvp, ace };
}
const offset = Object.fromEntries(roles.map(r => [r, 0]));
const pc = o => roles.map(r => `${r} ${Math.round((100 * o[r]) / plain.length)} %`).join(', ');
const before = shares({ norm, quant, offset });
for (let it = 0; it < 30; it++) {
  const { mvp, ace } = shares({ norm, quant, offset });
  for (const r of roles) offset[r] += 0.8 * (0.2 - (mvp[r] + ace[r]) / (2 * plain.length));
}
for (const r of roles) offset[r] = +offset[r].toFixed(3);
const after = shares({ norm, quant, offset });
console.log(`${sets.length} Summoner's Rift games, ${others.length} player games of other players, ${plain.length} games without an own account`);
console.log(`without the offsets – MVP: ${pc(before.mvp)}; ACE: ${pc(before.ace)}`);
console.log(`with them           – MVP: ${pc(after.mvp)}; ACE: ${pc(after.ace)}`);

const day = new Date().toISOString().slice(0, 10);
const out = `// Generated by tools/mvp-calibrate.js on ${day} from ${sets.length} Summoner's Rift games
// (${others.length} player games of other players) – don't edit by hand, run the tool again.
// ui/mvp.js explains the figures: norm = the usual value and spread of each part per role and
// result (W won, L lost), quant = the quantiles of the weighted sum, offset = per role, so that
// every role is MVP and ACE equally often.
(function (root) {
  const R = ${JSON.stringify({ games: sets.length, norm, quant, offset })};
  if (typeof module !== 'undefined' && module.exports) module.exports = R;
  else root.MvpRules = R;
})(typeof window !== 'undefined' ? window : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'ui', 'mvp-rules.js'), out);
console.log('ui/mvp-rules.js written');
