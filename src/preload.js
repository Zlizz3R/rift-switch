const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getState: () => ipcRenderer.invoke('get-state'),
  getHistory: puuid => ipcRenderer.invoke('get-history', puuid),
  live: () => ipcRenderer.invoke('live'),
  champions: () => ipcRenderer.invoke('champions'),
  matchup: (mine, enemy, lane) => ipcRenderer.invoke('matchup', mine, enemy, lane),
  rankedGames: puuid => ipcRenderer.invoke('ranked-games', puuid),
  tool: what => ipcRenderer.invoke('tool', what),
  openMulti: (region, ids) => ipcRenderer.invoke('open-multi', region, ids),
  onState: fn => ipcRenderer.on('state', (_e, s) => fn(s)),
  switchTo: puuid => ipcRenderer.invoke('switch', puuid),
  addSaved: data => ipcRenderer.invoke('add-saved', data),
  addNew: cred => ipcRenderer.invoke('add-new', cred || null),
  dismissLogin: () => ipcRenderer.invoke('dismiss-login'),
  getCredUser: puuid => ipcRenderer.invoke('get-cred-user', puuid),
  setCred: (puuid, cred) => ipcRenderer.invoke('set-cred', puuid, cred),
  delCred: puuid => ipcRenderer.invoke('del-cred', puuid),
  addCurrent: () => ipcRenderer.invoke('add-current'),
  cancelAdd: () => ipcRenderer.invoke('cancel-add'),
  remove: puuid => ipcRenderer.invoke('remove', puuid),
  setNote: (puuid, note) => ipcRenderer.invoke('note', puuid, note),
  reorder: order => ipcRenderer.invoke('reorder', order),
  arrange: list => ipcRenderer.invoke('arrange', list),
  catAdd: name => ipcRenderer.invoke('cat-add', name),
  catRename: (id, name) => ipcRenderer.invoke('cat-rename', id, name),
  catToggle: id => ipcRenderer.invoke('cat-toggle', id),
  catMove: (id, dir) => ipcRenderer.invoke('cat-move', id, dir),
  catDel: id => ipcRenderer.invoke('cat-del', id),
  refresh: () => ipcRenderer.invoke('refresh'),
  win: what => ipcRenderer.invoke('win', what),
  openExternal: url => ipcRenderer.invoke('open-external', url),
  setSetting: (k, v) => ipcRenderer.invoke('set-setting', k, v),
  onTraySwitch: fn => ipcRenderer.on('tray-switch', (_e, id) => fn(id)),
  onToast: fn => ipcRenderer.on('toast', (_e, msg) => fn(msg)),
});
